"""Domain ports have no dependencies on other project layers."""
from typing import Protocol

class DataPort(Protocol):
    def health(self) -> bool: ...
    def catalogue(self) -> list[dict]: ...
    def catalogue_item(self, code: str) -> dict | None: ...

class CollectionPort(Protocol):
    # TODO: implement application adapters and scenario-specific typed models.
    # Every operation must match BOTH collection code and session code.
    def create_or_get(self, session_code: str) -> dict: ...
    def read(self, collection_code: str, session_code: str) -> dict: ...
    def add(self, collection_code: str, session_code: str, entry: dict) -> None: ...
    def edit(self, collection_code: str, session_code: str, item_code: str, entry: dict) -> None: ...
    def remove(self, collection_code: str, session_code: str, item_code: str) -> None: ...
